/* Connect payment entry, transaction history, and account detail workflows. */
(() => {
  "use strict";

  function create(context) {
    const {
      $,
      state,
      dateOnly,
      fmtDate,
      esc,
      expenseCategoryLabel,
      money,
      monthStart,
      sumIncome,
      sumOperatingExpenses,
      postedOnOrAfter,
      toast,
      fetchAll,
      prettyType,
      todayIso,
      closeModal,
      populateFormOptions,
      fillSelect,
      openModal,
      previewReminderEmail,
      navigate,
      moneyInput,
      documentRef,
      paymentFrequencyLabel,
      accountBalance,
      amortizationSchedule,
      amountDueSince,
      unpaidDueAccrualStart,
      depositLedger,
      sumPosted,
      propertyAddress,
      EventClass,
      OptionClass,
    } = context;
    const entry = window.PropertyDeskEntryWorkflow.create({
      $,
      state,
      moneyInput,
      todayIso,
      toast,
      closeModal,
      fetchAll,
      populateFormOptions,
      fillSelect,
      prettyType,
      openModal,
      previewReminderEmail,
      navigate,
      documentRef,
    });
    const transactions = window.PropertyDeskTransactionWorkflow.create({
      $,
      state,
      dateOnly,
      fmtDate,
      esc,
      expenseCategoryLabel,
      money,
      monthStart,
      sumIncome,
      sumOperatingExpenses,
      postedOnOrAfter,
      toast,
      fetchAll,
      prettyType,
      openPayment: entry.openPayment,
      openExpense: entry.openExpense,
      updatePaymentGuidance: entry.updatePaymentGuidance,
      EventClass,
      OptionClass,
      documentRef,
    });
    const accountDetails = window.PropertyDeskAccountDetailsWorkflow.create({
      $,
      state,
      toast,
      fetchAll,
      money,
      moneyInput,
      todayIso,
      depositLedger,
      fmtDate,
      esc,
      closeModal,
      editAccount: entry.editAccount,
      openPayment: entry.openPayment,
      sumPosted,
      prettyType,
      paymentFrequencyLabel,
      accountBalance,
      amortizationSchedule,
      amountDueSince,
      unpaidDueAccrualStart,
      openModal,
      propertyAddress,
    });

    return {
      editAccount: entry.editAccount,
      updatePaymentGuidance: entry.updatePaymentGuidance,
      openPayment: entry.openPayment,
      openPropertyPayment: entry.openPropertyPayment,
      openExpense: entry.openExpense,
      attachEntryEvents: entry.attachEvents,
      openAccountForProperty: entry.openAccountForProperty,
      renderPayments: transactions.renderPayments,
      attachTransactionEvents: transactions.attachEvents,
      attachAccountDetailsEvents: accountDetails.attachEvents,
      openAccountDetails: accountDetails.openAccountDetails,
    };
  }

  window.PropertyDeskFinancialWorkspaceWorkflow = Object.freeze({ create });
})();

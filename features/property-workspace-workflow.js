/* Connect property details, overview, and portfolio actions. */
(() => {
  "use strict";

  function create(context) {
    const {
      $,
      state,
      toast,
      fetchAll,
      esc,
      money,
      fmtDate,
      prettyType,
      prettyKind,
      paymentFrequencyLabel,
      monthlyScheduledEstimate,
      accountBalance,
      amountDueSince,
      unpaidDueAccrualStart,
      todayIso,
      propertyAddress,
      streetAddress,
      collectedSince,
      scheduledMonthlyRunRate,
      monthStart,
      monthEnd,
      dateOnly,
      isPosted,
      lateReminderMailto,
      paymentStatusInMonth,
      sumIncome,
      sumOperatingExpenses,
      openModal,
      closeModal,
      openAccountDetails,
      editAccount,
      openPayment,
      openPropertyPayment,
      openExpense,
      resetAccountForm,
      populateFormOptions,
      documentRef = document,
    } = context;
    const { openPropertyDetails, attachEvents: attachPropertyDetailsEvents } =
      window.PropertyDeskPropertyDetailsWorkflow.create({
        $,
        state,
        isPosted,
        sumIncome,
        sumOperatingExpenses,
        money,
        fmtDate,
        esc,
        prettyType,
        paymentFrequencyLabel,
        accountBalance,
        openModal,
        propertyAddress,
        toast,
        fetchAll,
        todayIso,
        closeModal,
        editAccount,
        openPayment,
        openExpense,
        resetAccountForm,
        populateFormOptions,
        openAccountDetails,
        documentRef,
      });
    const { renderOverview, attachOverviewEvents } =
      window.PropertyDeskOverviewWorkflow.create({
        $,
        state,
        monthlyScheduledEstimate,
        accountBalance,
        amountDueSince,
        unpaidDueAccrualStart,
        todayIso,
        esc,
        prettyKind,
        money,
        propertyAddress,
        collectedSince,
        scheduledMonthlyRunRate,
        monthStart,
        isPosted,
        prettyType,
        fmtDate,
        openPropertyDetails,
        openPropertyPayment,
      });
    const { renderProperties, attachEvents: attachPropertyPortfolioEvents } =
      window.PropertyDeskPropertyPortfolioWorkflow.create({
        $,
        state,
        toast,
        fetchAll,
        esc,
        money,
        paymentFrequencyLabel,
        monthlyScheduledEstimate,
        accountBalance,
        amountDueSince,
        unpaidDueAccrualStart,
        todayIso,
        propertyAddress,
        monthStart,
        streetAddress,
        dateOnly,
        monthEnd,
        lateReminderMailto,
        paymentStatusInMonth,
        openPayment,
        openPropertyDetails,
        resetAccountForm,
        populateFormOptions,
        openModal,
      });

    return {
      attachPropertyDetailsEvents,
      renderOverview,
      attachOverviewEvents,
      renderProperties,
      attachPropertyPortfolioEvents,
    };
  }

  window.PropertyDeskPropertyWorkspaceWorkflow = Object.freeze({ create });
})();

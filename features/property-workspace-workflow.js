/* Connect property details, portfolio, and dashboard workflows. */
(() => {
  "use strict";

  function create(context) {
    const {
      $,
      state,
      isPosted,
      sumIncome,
      sumOperatingExpenses,
      money,
      fmtDate,
      esc,
      prettyType,
      paymentFrequencyLabel,
      accountBalance,
      openModal,
      propertyAddress,
      toast,
      fetchAll,
      todayIso,
      closeModal,
      editAccount,
      openPayment,
      openExpense,
      openPropertyPayment,
      openAccountForProperty,
      openAccountDetails,
      monthlyScheduledEstimate,
      amountDueSince,
      unpaidDueAccrualStart,
      prettyKind,
      collectedSince,
      scheduledMonthlyRunRate,
      monthStart,
      postedOnOrAfter,
      streetAddress,
      dateOnly,
      monthEnd,
      lateReminderMailto,
      paymentStatusInMonth,
    } = context;
    const { openPropertyDetails, attachEvents: attachPropertyDetailsEvents } =
      window.PropertyDeskPropertyDetailsWorkflow.create({
        $,
        state,
        isPosted,
        sumIncome,
        sumOperatingExpenses,
        money,
        fmtDate,
        esc,
        prettyType,
        paymentFrequencyLabel,
        accountBalance,
        openModal,
        propertyAddress,
        toast,
        fetchAll,
        todayIso,
        closeModal,
        editAccount,
        openPayment,
        openExpense,
        openAccountForProperty,
        openAccountDetails,
      });
    const { renderOverview, attachOverviewEvents } =
      window.PropertyDeskOverviewWorkflow.create({
        $,
        state,
        monthlyScheduledEstimate,
        accountBalance,
        amountDueSince,
        unpaidDueAccrualStart,
        todayIso,
        esc,
        prettyKind,
        money,
        propertyAddress,
        collectedSince,
        scheduledMonthlyRunRate,
        monthStart,
        isPosted,
        postedOnOrAfter,
        prettyType,
        fmtDate,
        openPropertyDetails,
        openPropertyPayment,
      });
    const { renderProperties, attachEvents: attachPropertyPortfolioEvents } =
      window.PropertyDeskPropertyPortfolioScreenWorkflow.create({
        $,
        state,
        esc,
        money,
        paymentFrequencyLabel,
        monthlyScheduledEstimate,
        accountBalance,
        amountDueSince,
        unpaidDueAccrualStart,
        todayIso,
        propertyAddress,
        streetAddress,
        monthStart,
        dateOnly,
        monthEnd,
        lateReminderMailto,
        paymentStatusInMonth,
        toast,
        fetchAll,
        openPayment,
        openPropertyDetails,
        openAccountForProperty,
      });

    return {
      openPropertyDetails,
      renderOverview,
      attachOverviewEvents,
      renderProperties,
      attachPropertyPortfolioEvents,
      attachPropertyDetailsEvents,
    };
  }

  window.PropertyDeskPropertyWorkspaceWorkflow = Object.freeze({ create });
})();
